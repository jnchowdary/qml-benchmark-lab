#!/usr/bin/env python3
r"""Turn docs/paper.md into a self-contained arXiv submission bundle.

WHY THIS EXISTS
---------------
arXiv wants LaTeX source and compiles the PDF itself, so the submission is a
directory of `.tex` and figures rather than a document. `scripts/paper_to_docx.js`
produces the Word version from the same markdown; this produces the LaTeX one.
Both read `docs/paper.md`, which `scripts/assemble_paper.py` generates, so there
is one source and two renderings rather than three documents.

WHY TWO CHARACTER MAPS AND NOT ONE
----------------------------------
On 24 October 2026 a blind single-character substitution over the whole file was
tried and produced a document that built with **zero warnings** and was wrong in
four places. Reading the rendered pages, not the build log, is what found them:

  * `ó` mapped to a LaTeX accent came out as the literal `Fl'{o}rez Ablan`, in a
    heading, mangling a co-author's name this project has already got wrong
    twice. Accented Latin needs no mapping at all; pandoc handles it.
  * `−` mapped to `$-$` printed as literal dollar signs, because pandoc will not
    close inline math when the next character is a digit, and in this paper the
    minus sign precedes a digit almost every time it appears.
  * `√` mapped alone left an empty radical with a stray `N` beside it. The root
    sign is always followed by `N` or `n` here, so it is a two-character
    sequence, as are `⁻¹` and `⁻²`, which a single-character map split into two
    superscripts.
  * 46 dollar signs leaked into the paper's four-space blocks, because a blind
    replace does not know what verbatim is.

So: TEXT_SEQ and TEXT_CHARS apply to prose only, longest sequences first;
CODE_CHARS applies only inside verbatim regions and transliterates to ASCII,
because LaTeX verbatim cannot render `λ` or `‖` under pdflatex whatever the
prose does. Both maps are declared here rather than inferred, and anything not
in them is a refusal rather than a silent pass.

WHAT IT REFUSES TO DO
---------------------
  * leave any non-ASCII character unmapped, naming the character and its line
  * introduce `$` or `\` into a verbatim region, which is the 46-leak defect
  * emit `\includegraphics` with a parent-directory path, which arXiv rejects,
    or reference a figure the bundle does not contain

Usage:
    conda run -n pandoc python3 scripts/paper_to_latex.py
    python3 scripts/paper_to_latex.py --pandoc /path/to/pandoc
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

SEQSPLIT_MIN = 40          # shorter spans fit a line and need no breaking

HEADER = r"""% Generated by scripts/paper_to_latex.py; submitted with the bundle.
% Software Heritage identifiers are 50 unbroken hexadecimal characters and
% appear both inline and in a verbatim block. Without these the inline one runs
% 123pt past the right margin and the block 66pt.
\usepackage{fvextra}
\DefineVerbatimEnvironment{verbatim}{Verbatim}{breaklines=true,breakanywhere=true}
\usepackage{seqsplit}
\setlength{\emergencystretch}{4em}
"""

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "paper.md"
BUNDLE = ROOT / "arxiv"
MANIFEST = ROOT / "docs" / "latex-manifest.json"

# Prose. Longest sequences first: `⁻¹` is one superscript, not two, and the
# radical always covers the letter after it.
TEXT_SEQ = [
    ("⁻¹", r"$^{-1}$"), ("⁻²", r"$^{-2}$"),
    ("√N", r"$\sqrt{N}$"), ("√n", r"$\sqrt{n}$"),
]

TEXT_CHARS = {
    "—": "---", "–": "--", "…": r"\ldots{}", "·": r"$\cdot$",
    "§": r"\S{}", "†": r"$\dagger$",
    "λ": r"$\lambda$", "μ": r"$\mu$", "α": r"$\alpha$", "π": r"$\pi$",
    "Σ": r"$\Sigma$",
    # A hyphen, NOT $-$. Pandoc will not close inline math before a digit, and
    # 46 of this paper's minus signs are followed by one.
    "−": "-",
    "×": r"$\times$", "≤": r"$\le$", "≥": r"$\ge$", "≠": r"$\ne$",
    "≈": r"$\approx$", "∝": r"$\propto$", "∈": r"$\in$", "∞": r"$\infty$",
    "→": r"$\to$", "‖": r"$\|$", "⟨": r"$\langle$", "⟩": r"$\rangle$",
    "¹": r"$^{1}$", "²": r"$^{2}$", "₁": r"$_{1}$", "₂": r"$_{2}$",
    # 'ó' is deliberately absent. Mapping it produced the literal Fl'{o}rez.
}

# Verbatim. ASCII only: LaTeX verbatim under pdflatex cannot set these glyphs,
# and a dollar sign here is a leak rather than maths. Only one block in this
# paper needs it, the F19 formula in §2.2, and it is transliterated rather than
# dropped so the formula still reads.
CODE_CHARS = {
    "⁻¹": "^-1", "⁻²": "^-2", "¹": "^1", "²": "^2", "₁": "_1", "₂": "_2",
    "‖": "||", "∞": "inf", "λ": "lambda", "μ": "mu", "√": "sqrt",
    "→": "->", "−": "-", "—": "--", "≤": "<=", "≥": ">=", "·": ".",
    "…": "...", "√": "sqrt", "∈": "in", "×": "x", "≠": "!=", "≈": "~=",
    "α": "alpha", "π": "pi", "Σ": "Sigma", "§": "sec.", "†": "+",
    "⟨": "<", "⟩": ">", "∝": "prop-to", "–": "-",
}

FENCE = re.compile(r"^\s*```")
INDENTED = re.compile(r"^ {4}\S")
BLANK = re.compile(r"^\s*$")


def split_code_spans(line):
    """(text, is_code) runs for one prose line, splitting on backtick spans.

    A backtick span holds identifiers like `K_ij` and `n_qubits`. Substituting
    inside one changes what the paper says a field is called.
    """
    out, i = [], 0
    for m in re.finditer(r"`[^`]*`", line):
        if m.start() > i:
            out.append((line[i:m.start()], False))
        out.append((m.group(0), True))
        i = m.end()
    if i < len(line):
        out.append((line[i:], False))
    return out or [("", False)]


def apply_text(s):
    for a, b in TEXT_SEQ:
        s = s.replace(a, b)
    for a, b in TEXT_CHARS.items():
        s = s.replace(a, b)
    return s


def apply_code(s):
    for a, b in CODE_CHARS.items():
        s = s.replace(a, b)
    return s


def convert(md):
    """Substitute prose and verbatim separately. Returns (text, problems)."""
    lines = md.split("\n")
    out, problems = [], []
    fenced = False
    i = 0
    while i < len(lines):
        line = lines[i]

        if FENCE.match(line):
            fenced = not fenced
            out.append(apply_code(line))
            i += 1
            continue
        if fenced:
            out.append(apply_code(line))
            i += 1
            continue

        # a four-space block runs until a non-blank, non-indented line
        if INDENTED.match(line):
            while i < len(lines) and (lines[i].startswith("    ") or BLANK.match(lines[i])):
                if BLANK.match(lines[i]) and not (
                        i + 1 < len(lines) and INDENTED.match(lines[i + 1])):
                    break
                out.append(apply_code(lines[i]))
                i += 1
            continue

        # A code span is verbatim in LaTeX, so it takes the ASCII map and not
        # the prose one. Skipping it entirely, as the first version did, left
        # `K²` and `‖` unmapped and the refusal below caught it.
        out.append("".join(apply_code(seg) if code else apply_text(seg)
                           for seg, code in split_code_spans(line)))
        i += 1

    text = "\n".join(out)

    for n, line in enumerate(text.split("\n"), 1):
        for ch in line:
            if ord(ch) > 127 and ch != "ó":
                problems.append(f"line {n}: U+{ord(ch):04X} {ch!r} is not in either map")
                break
    return text, problems


def verbatim_is_clean(text):
    """No `$` or backslash may have reached a verbatim region. That defect put
    46 dollar signs into the first build and the build reported no warnings."""
    bad, fenced = [], False
    for n, line in enumerate(text.split("\n"), 1):
        if FENCE.match(line):
            fenced = not fenced
            continue
        if fenced or INDENTED.match(line):
            if "$" in line or "\\" in line:
                bad.append(f"line {n}: {line.strip()[:70]}")
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pandoc", default="pandoc", help="path to the pandoc binary")
    a = ap.parse_args()

    if not SOURCE.exists():
        raise SystemExit(f"\n  {SOURCE} does not exist. Run scripts/assemble_paper.py.\n")

    md = SOURCE.read_text(encoding="utf-8")
    text, problems = convert(md)
    problems += [f"verbatim leak, {b}" for b in verbatim_is_clean(text)]
    if problems:
        raise SystemExit("\n  REFUSING to convert; nothing was written.\n" +
                         "".join(f"    - {p}\n" for p in problems[:25]) +
                         (f"    ... and {len(problems) - 25} more\n"
                          if len(problems) > 25 else ""))

    try:
        version = subprocess.check_output([a.pandoc, "--version"], text=True).split("\n")[0]
    except (OSError, subprocess.CalledProcessError) as e:
        raise SystemExit(f"\n  cannot run pandoc ({a.pandoc}): {e}\n"
                         f"  conda run -n pandoc python3 scripts/paper_to_latex.py\n")

    BUNDLE.mkdir(exist_ok=True)

    # The preamble pandoc's template does not provide. Software Heritage
    # identifiers are 50 unbroken hexadecimal characters and appear inline and
    # in a verbatim block; without these the inline one ran 123pt past the
    # margin and the block 66pt. Measured on the same bundle, these three lines
    # plus the targeted substitution below take the overfull count from 14 to 6
    # and the worst from 123pt to 43pt, with no new errors and no page or
    # figure change. The remainder are prose paragraphs and are left alone.
    header = BUNDLE / "header.tex"
    header.write_text(HEADER, encoding="utf-8")

    staged = BUNDLE / "paper_source.md"
    staged.write_text(text, encoding="utf-8")

    tex = BUNDLE / "paper.tex"
    subprocess.run([a.pandoc, str(staged), "-s", "-o", str(tex), "--toc",
                    "-H", header.name,
                    "-V", "geometry:margin=1in", "-V", "fontsize=10pt"],
                   check=True, cwd=BUNDLE)

    # arXiv takes a flat bundle and rejects parent-directory references.
    body = tex.read_text(encoding="utf-8")

    # Let the long identifiers break. ONLY spans with no control sequence:
    # 73 of this paper's 166 texttt spans contain things like \\_ and \\^{},
    # and seqsplit walks its argument token by token, so redefining texttt
    # globally produced 12 LaTeX errors on the first attempt.
    split, permitted = [], []

    def _breakable(m):
        inner = m.group(1)
        if len(inner) >= SEQSPLIT_MIN and "\\" not in inner:
            split.append(inner)
            return "\\texttt{\\seqsplit{" + inner + "}}"
        # A span seqsplit declines still has to fit the line, and on 26 October
        # 2026 three did not: `scripts/foreign/kakavand_adapter.py` ran 43.2pt
        # past the right margin, `scripts/check_paper_figures.py` 41.6pt, and
        # the dataset slug `blastchar/telco-customer-churn` 8.9pt. All three are
        # under SEQSPLIT_MIN and two contain \_, so they fail both of the
        # conditions above.
        #
        # \allowbreak PERMITS a break and never forces one, and unlike seqsplit
        # it walks nothing, so a span containing \_ or \^{} is unaffected --
        # which is what made the global seqsplit redefinition produce 12 errors.
        # It is inserted after a separator only, so a break can land where a
        # reader already expects one, as the url package does. There is no
        # length threshold: adding a break opportunity to a span that fits
        # changes nothing about how it sets.
        #
        # The separator must be a path slash and NOT the one in pandoc's italic
        # correction
        # `\\/`, which it emits between the hyphens of `--flag` to stop the
        # ligature. Inserting a break there let `--check` split into `-` and
        # `-check` across a line, which the first draft of this did.
        if re.search(r"(?<!\\)/", inner) or "\\_" in inner:
            permitted.append(inner)
            inner = re.sub(r"(?<!\\)/", "/\\\\allowbreak{}", inner)
            inner = inner.replace("\\_", "\\_\\allowbreak{}")
            return "\\texttt{" + inner + "}"
        return m.group(0)

    # re.subn's count is every match, including the ones this declines, so it
    # would report all 166 spans as split. The counter is explicit for that
    # reason: a number that measures nothing reads as evidence.
    body = re.sub(r"\\texttt\{([^}]*)\}", _breakable, body)
    n_split = len(split)

    figures = []
    for m in re.finditer(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", body):
        src = (SOURCE.parent / m.group(1)).resolve()
        if not src.exists():
            raise SystemExit(f"\n  figure referenced but not found: {m.group(1)}\n")
        shutil.copy2(src, BUNDLE / src.name)
        body = body.replace("{" + m.group(1) + "}", "{" + src.name + "}")
        figures.append(src.name)
    tex.write_text(body, encoding="utf-8")

    left = re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]*\.\.[^}]*)\}", body)
    if left:
        raise SystemExit(f"\n  parent-directory figure paths survive: {left}\n")

    MANIFEST.write_text(json.dumps({
        "note": "Written by scripts/paper_to_latex.py. The bundle in arxiv/ is "
                "generated from docs/paper.md and is what would be submitted. "
                "This file records the pandoc that built it, because pandoc's "
                "LaTeX writer and template differ across major versions.",
        "source": "docs/paper.md",
        "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "pandoc": version,
        "figures": sorted(figures),
        "seqsplit_spans": n_split,
        "allowbreak_spans": len(permitted),
    }, indent=2) + "\n", encoding="utf-8")

    print(f"\n  -> {tex.relative_to(ROOT)}  "
          f"({len(body.splitlines())} lines, {len(body):,} bytes)")
    print(f"  {len(figures)} figure(s) copied flat: {', '.join(sorted(figures))}")
    print(f"  {n_split} span(s) seqsplit, {len(permitted)} given break "
          f"opportunities after a separator")
    print(f"  {version}")
    print(f"  provenance -> {MANIFEST.relative_to(ROOT)}\n")
    print("  arXiv compiles this itself; no local TeX is needed to submit.\n")


if __name__ == "__main__":
    main()
